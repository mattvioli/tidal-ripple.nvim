local struct = require("tidal.lib.losc.lib.struct")

describe("losc.lib.struct", function()
  describe("integer pack/unpack big-endian", function()
    it("packs i4", function()
      local packed = struct.pack(">i4", 42)
      assert.equals(4, #packed)
      local value, next = struct.unpack(">i4", packed)
      assert.equals(42, value)
      assert.equals(5, next)
    end)

    it("round-trips signed integers", function()
      for _, n in ipairs({ 0, 1, -1, 128, -128, 32767, -32768, 2147483647, -2147483648 }) do
        local packed = struct.pack(">i4", n)
        local value = struct.unpack(">i4", packed)
        assert.equals(n, value)
      end
    end)

    it("round-trips unsigned integers", function()
      local packed = struct.pack(">I4", 4294967295)
      local value = struct.unpack(">I4", packed)
      assert.equals(4294967295, value)
    end)
  end)

  describe("float pack/unpack", function()
    it("round-trips zero", function()
      local packed = struct.pack(">f", 0.0)
      local value = struct.unpack(">f", packed)
      assert.equals(0.0, value)
    end)

    it("round-trips a float", function()
      local packed = struct.pack(">f", 3.14159)
      local value = struct.unpack(">f", packed)
      assert.is_near(3.14159, value, 0.0001)
    end)

    it("round-trips negative floats", function()
      local packed = struct.pack(">f", -1.5)
      local value = struct.unpack(">f", packed)
      assert.is_near(-1.5, value, 0.0001)
    end)
  end)

  describe("double pack/unpack", function()
    it("round-trips a double", function()
      local packed = struct.pack(">d", 3.141592653589793)
      local value = struct.unpack(">d", packed)
      assert.is_near(3.141592653589793, value, 1e-10)
    end)
  end)

  describe("string pack/unpack", function()
    it("packs c-strings", function()
      local packed = struct.pack(">c4", "abcd")
      assert.equals("abcd", packed)
      local value = struct.unpack(">c4", packed)
      assert.equals("abcd", value)
    end)
  end)
end)

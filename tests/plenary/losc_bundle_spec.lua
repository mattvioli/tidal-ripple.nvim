local Bundle = require("tidal.lib.losc.bundle")
local Message = require("tidal.lib.losc.message")
local Timetag = require("tidal.lib.losc.timetag")

describe("losc.bundle", function()
  describe("Bundle.new", function()
    it("creates empty bundle", function()
      local b = Bundle.new(Timetag.new_raw(100, 0))
      assert.equals(100, b.content.timetag.seconds)
      assert.equals(0, #b.content - 1)
    end)

    it("creates a bundle with default empty content", function()
      local b = Bundle.new()
      assert.is_table(b.content)
      assert.equals(nil, b.content.timetag)
    end)

    it("adds messages via constructor args", function()
      local m = Message.new("/test")
      m:add("i", 1)
      local b = Bundle.new(Timetag.new_raw(100, 0), m)
      assert.equals(1, #b.content - 1)
    end)
  end)

  describe("Bundle:timetag", function()
    it("returns the timetag", function()
      local b = Bundle.new(Timetag.new_raw(100, 0))
      local tt = b:timetag()
      assert.equals(100, tt:seconds())
    end)

    it("sets the timetag when given one", function()
      local b = Bundle.new(Timetag.new_raw(100, 0))
      b:timetag(Timetag.new_raw(200, 0))
      assert.equals(200, b:timetag():seconds())
    end)
  end)

  describe("Bundle.tbl_validate", function()
    it("accepts a valid table", function()
      assert.is_true(pcall(Bundle.tbl_validate, { timetag = { seconds = 1, fractions = 1 } }))
    end)

    it("rejects a missing timetag", function()
      assert.has.errors(function()
        Bundle.tbl_validate({})
      end)
    end)
  end)

  describe("pack/unpack round-trip", function()
    it("round-trips a bundle with one message", function()
      local tt = Timetag.new(1000, 500, 10000)
      local b = Bundle.new(tt)
      local m = Message.new("/dirt/play")
      m:add("i", 1)
      m:add("s", "bd")
      b:add(m)

      local packed = Bundle.pack(b.content)
      local unpacked = Bundle.unpack(packed)

      assert.equals("#bundle", packed:sub(1, 7))
      assert.equals(1, #unpacked)
      assert.equals("/dirt/play", unpacked[1].address)
      assert.equals("is", unpacked[1].types)
      assert.equals(1, unpacked[1][1])
      assert.equals("bd", unpacked[1][2])
    end)

    it("round-trips nested bundles", function()
      local tt = Timetag.new(1000, 0, 10000)
      local inner_b = Bundle.new(tt)
      inner_b:add(Message.new("/inner"))

      local outer_b = Bundle.new(tt)
      outer_b:add(Message.new("/outer"))
      outer_b:add(inner_b)

      local packed = Bundle.pack(outer_b.content)
      local unpacked = Bundle.unpack(packed)

      assert.equals(2, #unpacked)
      assert.equals("/outer", unpacked[1].address)
      assert.is_table(unpacked[2])
      assert.equals(1, #unpacked[2])
      assert.equals("/inner", unpacked[2][1].address)
    end)

    it("validates bundle bytes", function()
      local tt = Timetag.new(1000, 500, 10000)
      local b = Bundle.new(tt)
      b:add(Message.new("/test"))
      local packed = Bundle.pack(b.content)
      assert.is_true(pcall(Bundle.bytes_validate, packed))
    end)
  end)
end)

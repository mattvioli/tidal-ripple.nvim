local Timetag = require("tidal.lib.losc.timetag")

describe("losc.timetag", function()
  describe("Timetag.new_raw", function()
    it("defaults to seconds=0 fractions=1", function()
      local tt = Timetag.new_raw()
      assert.equals(0, tt:seconds())
      assert.equals(1, tt:fractions())
    end)

    it("accepts a number as seconds", function()
      local tt = Timetag.new_raw(100)
      assert.equals(100, tt:seconds())
    end)

    it("accepts two numbers as seconds/fractions", function()
      local tt = Timetag.new_raw(100, 200)
      assert.equals(100, tt:seconds())
      assert.equals(200, tt:fractions())
    end)

    it("accepts a table", function()
      local tt = Timetag.new_raw({ seconds = 5, fractions = 6 })
      assert.equals(5, tt:seconds())
      assert.equals(6, tt:fractions())
    end)
  end)

  describe("Timetag.new", function()
    it("adds NTP offset to seconds", function()
      local tt = Timetag.new(10, 0, 1000)
      assert.equals(10 + 2208988800, tt:seconds())
    end)

    it("computes fractions from value within precision", function()
      local tt = Timetag.new(0, 500, 1000)
      assert.is_near(2147483648, tt:fractions(), 1)
    end)

    it("defaults precision to 1000", function()
      local tt = Timetag.new(10, 0)
      assert.equals(10 + 2208988800, tt:seconds())
    end)

    it("handles missing args", function()
      local tt = Timetag.new()
      assert.equals(2208988800, tt:seconds())
      assert.equals(0, tt:fractions())
    end)
  end)

  describe("Timetag.new_from_timestamp", function()
    it("creates timetag from timestamp", function()
      local tt = Timetag.new_from_timestamp(5000, 1000)
      assert.equals(5, tt:seconds() - 2208988800)
    end)

    it("handles fractional timestamps", function()
      local tt = Timetag.new_from_timestamp(4500, 1000)
      assert.equals(4, tt:seconds() - 2208988800)
    end)
  end)

  describe("timestamp round-trip", function()
    it("round-trips through NTP", function()
      local tt = Timetag.new_from_timestamp(12345, 1000)
      local ts = tt:timestamp(1000)
      assert.is_near(12345, ts, 1)
    end)
  end)

  describe("arithmetic", function()
    it("adds a number to a timetag", function()
      local tt = Timetag.new_raw(100, 0)
      local result = tt + 5
      assert.equals(105, result:seconds())
    end)

    it("adds number on left", function()
      local tt = Timetag.new_raw(100, 0)
      local result = 5 + tt
      assert.equals(105, result:seconds())
    end)
  end)

  describe("pack/unpack", function()
    it("round-trips a timetag", function()
      local tt = Timetag.new(12345, 678, 10000)
      local packed = Timetag.pack(tt.content)
      assert.equals(8, #packed)
      local unpacked, next_offset = Timetag.unpack(packed)
      assert.equals(tt.content.seconds, unpacked.seconds)
      assert.equals(tt.content.fractions, unpacked.fractions)
      assert.equals(9, next_offset)
    end)
  end)
end)

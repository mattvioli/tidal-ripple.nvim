local Message = require("tidal.lib.losc.message")

describe("losc.message", function()
  describe("Message.new", function()
    it("creates empty message", function()
      local m = Message.new()
      assert.equals("", m:address())
      assert.equals("", m:types())
      assert.are.same({}, m:args())
    end)

    it("accepts string address without slash and prepends it", function()
      local m = Message.new("test")
      assert.equals("/test", m:address())
    end)

    it("accepts string address with slash", function()
      local m = Message.new("/test")
      assert.equals("/test", m:address())
    end)

    it("accepts table", function()
      local m = Message.new({ address = "/test", types = "" })
      assert.equals("/test", m:address())
      assert.equals("", m:types())
    end)

    it("rejects invalid address characters", function()
      assert.has.errors(function()
        Message.new("bad address")
      end)
    end)
  end)

  describe("Message:add", function()
    it("adds typed arguments", function()
      local m = Message.new("/test")
      m:add("i", 42)
      m:add("f", 3.14)
      m:add("s", "hello")
      assert.equals("ifs", m:types())
      assert.are.same({ 42, 3.14, "hello" }, m:args())
    end)

    it("adds T and F with no item", function()
      local m = Message.new("/test")
      m:add("T")
      m:add("F")
      assert.equals("TF", m:types())
      assert.are.same({ true, false }, m:args())
    end)

    it("adds N and I with no item", function()
      local m = Message.new("/test")
      m:add("N")
      m:add("I")
      assert.equals("NI", m:types())
      assert.are.same({ false, math.huge }, m:args())
    end)
  end)

  describe("Message:iter", function()
    it("iterates over types and args", function()
      local m = Message.new("/test")
      m:add("i", 1)
      m:add("s", "a")
      local collected = {}
      for _, type, arg in m:iter() do
        collected[#collected + 1] = { type = type, arg = arg }
      end
      assert.equals(2, #collected)
      assert.equals("i", collected[1].type)
      assert.equals(1, collected[1].arg)
      assert.equals("s", collected[2].type)
      assert.equals("a", collected[2].arg)
    end)
  end)

  describe("Message.tbl_validate", function()
    it("accepts valid table", function()
      assert.is_true(pcall(Message.tbl_validate, { address = "/x", types = "" }))
    end)

    it("rejects missing address", function()
      assert.has.errors(function()
        Message.tbl_validate({ types = "" })
      end)
    end)

    it("rejects missing types", function()
      assert.has.errors(function()
        Message.tbl_validate({ address = "/x" })
      end)
    end)

    it("rejects type-count mismatch", function()
      assert.has.errors(function()
        Message.tbl_validate({ address = "/x", types = "i", 1, 2 })
      end)
    end)
  end)

  describe("pack/unpack round-trip", function()
    it("round-trips a message with mixed types", function()
      local m = Message.new("/dirt/play")
      m:add("i", 1)
      m:add("f", 0.5)
      m:add("s", "bd")
      local packed = Message.pack(m.content)
      local unpacked, _ = Message.unpack(packed)
      assert.equals("/dirt/play", unpacked.address)
      assert.equals("ifs", unpacked.types)
      assert.equals(1, unpacked[1])
      assert.is_near(0.5, unpacked[2], 0.0001)
      assert.equals("bd", unpacked[3])
    end)

    it("round-trips an empty args message", function()
      local m = Message.new("/hush")
      local packed = Message.pack(m.content)
      local unpacked, _ = Message.unpack(packed)
      assert.equals("/hush", unpacked.address)
      assert.equals("", unpacked.types)
    end)
  end)
end)

local Packet = require("tidal.lib.losc.packet")
local Message = require("tidal.lib.losc.message")
local Timetag = require("tidal.lib.losc.timetag")

describe("losc.packet", function()
  describe("Packet.is_bundle", function()
    it("detects bundle strings", function()
      local tt = Timetag.new_raw(100, 0)
      local Bundle = require("tidal.lib.losc.bundle")
      local b = Bundle.new(tt)
      b:add(Message.new("/test"))
      local packed = Bundle.pack(b.content)
      assert.is_true(Packet.is_bundle(packed))
    end)

    it("detects non-bundle strings", function()
      local m = Message.new("/test")
      m:add("i", 42)
      local packed = Message.pack(m.content)
      assert.is_false(Packet.is_bundle(packed))
    end)

    it("detects bundle tables by timetag", function()
      assert.is_true(Packet.is_bundle({ timetag = { seconds = 1, fractions = 1 } }))
    end)

    it("detects non-bundle tables", function()
      assert.is_false(Packet.is_bundle({ address = "/x", types = "" }))
    end)
  end)

  describe("Packet.pack/unpack round-trip", function()
    it("round-trips a message", function()
      local m = Message.new("/dirt/play")
      m:add("i", 1)
      m:add("f", 0.25)
      local packed = Packet.pack(m.content)
      local unpacked = Packet.unpack(packed)
      assert.equals("/dirt/play", unpacked.address)
      assert.equals("if", unpacked.types)
      assert.equals(1, unpacked[1])
    end)

    it("round-trips a bundle", function()
      local Bundle = require("tidal.lib.losc.bundle")
      local b = Bundle.new(Timetag.new_raw(100, 0))
      b:add(Message.new("/one"))
      b:add(Message.new("/two"))
      local packed = Packet.pack(b.content)
      local unpacked = Packet.unpack(packed)
      assert.equals(2, #unpacked)
      assert.equals("/one", unpacked[1].address)
      assert.equals("/two", unpacked[2].address)
    end)
  end)
end)

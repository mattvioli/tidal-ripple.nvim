local Types = require("tidal.lib.losc.types")

describe("losc.types", function()
  describe("Types.get", function()
    it("returns the keys of a table", function()
      local result = Types.get({ a = 1, b = 2 })
      table.sort(result)
      assert.are.same({ "a", "b" }, result)
    end)

    it("returns empty for empty table", function()
      assert.are.same({}, Types.get({}))
    end)
  end)

  describe("pack/unpack strings", function()
    it("round-trips a string", function()
      local packed = Types.pack("s", "hello")
      local value, next_offset = Types.unpack("s", packed)
      assert.equals("hello", value)
      assert.equals(#packed + 1, next_offset)
    end)

    it("pads strings to 4-byte boundaries", function()
      local packed = Types.pack("s", "abcd")
      assert.equals(8, #packed)
      local value = Types.unpack("s", packed)
      assert.equals("abcd", value)
    end)

    it("pads strings not aligned to 4 bytes", function()
      local packed = Types.pack("s", "abc")
      assert.equals(8, #packed)
      local value = Types.unpack("s", packed)
      assert.equals("abc", value)
    end)
  end)

  describe("pack/unpack integers", function()
    it("round-trips an integer", function()
      local packed = Types.pack("i", 42)
      local value = Types.unpack("i", packed)
      assert.equals(42, value)
    end)

    it("round-trips a negative integer", function()
      local packed = Types.pack("i", -42)
      local value = Types.unpack("i", packed)
      assert.equals(-42, value)
    end)
  end)

  describe("pack/unpack floats", function()
    it("round-trips a float", function()
      local packed = Types.pack("f", 3.14)
      local value = Types.unpack("f", packed)
      assert.is_near(3.14, value, 0.0001)
    end)
  end)

  describe("pack/unpack blobs", function()
    it("round-trips a blob", function()
      local blob = "blobdata"
      local packed = Types.pack("b", blob)
      local value = Types.unpack("b", packed)
      assert.equals(blob, value)
    end)
  end)

  describe("pack/unpack timetags", function()
    it("round-trips a timetag", function()
      local Timetag = require("tidal.lib.losc.timetag")
      local tt = Timetag.new(12345, 678)
      local packed = Types.pack("t", tt.content)
      local value = Types.unpack("t", packed)
      assert.equals(tt.content.seconds, value.seconds)
      assert.equals(tt.content.fractions, value.fractions)
    end)
  end)

  describe("pack/unpack double", function()
    it("round-trips a double", function()
      local packed = Types.pack("d", 3.141592653589793)
      local value = Types.unpack("d", packed)
      assert.is_near(3.141592653589793, value, 0.0000000001)
    end)
  end)

  describe("special types", function()
    it("unpacks T as true", function()
      local value, offset = Types.unpack("T", {}, 0)
      assert.is_true(value)
      assert.equals(0, offset)
    end)

    it("unpacks F as false", function()
      local value = Types.unpack("F", {}, 0)
      assert.is_false(value)
    end)

    it("unpacks N as false", function()
      local value = Types.unpack("N", {}, 0)
      assert.is_false(value)
    end)

    it("unpacks I as inf", function()
      local value = Types.unpack("I", {}, 0)
      assert.equals(math.huge, value)
    end)
  end)
end)
